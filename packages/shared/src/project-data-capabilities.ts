export type DataCapabilityGroup = keyof typeof DATA_CAPABILITY_GROUPS;

export function isDataCapabilityPermitted(agentTools: string[], capabilityId: string): boolean {
  const normTools = (agentTools ?? []).map((t) => t.trim().toLowerCase());
  if (normTools.includes("*") || normTools.includes("all")) return true;
  if (normTools.includes("project.data.*") || normTools.includes("data.*")) return true;
  if (normTools.includes(capabilityId.toLowerCase())) return true;

  for (const [groupName, tools] of Object.entries(DATA_CAPABILITY_GROUPS)) {
    if (normTools.includes(groupName) || normTools.includes(`project.${groupName}`)) {
      if ((tools as readonly string[]).includes(capabilityId)) return true;
    }
  }
  return false;
}

