import type { PoolClient } from "pg";

export async function runMigration060(client: PoolClient) {
  await client.query([
    "CREATE TABLE data_backends (",
    "id text PRIMARY KEY, workspace_id text NOT NULL, company_id text NOT NULL, created_by text NOT NULL,",
    "name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 200),",
    "provider text NOT NULL CHECK (provider IN ('shared_postgres','external_postgres')),",
    "status text NOT NULL DEFAULT 'provisioning' CHECK (status IN ('provisioning','ready','unavailable','archived','deleting')),",
    "created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),",
    "UNIQUE(workspace_id,company_id,id),",
    "FOREIGN KEY(workspace_id,company_id,created_by) REFERENCES companies(workspace_id,id,user_id) ON DELETE RESTRICT",
    ");",
    "CREATE INDEX data_backends_company_idx ON data_backends(workspace_id,company_id,created_by,updated_at DESC);",
    "CREATE TABLE data_backend_secrets (",
    "id text PRIMARY KEY, backend_id text NOT NULL, environment text NOT NULL CHECK(environment IN ('dev','prod')),",
    "role text NOT NULL CHECK(role IN ('migrator','runtime','signing')), encrypted_value text NOT NULL,",
    "created_at timestamptz NOT NULL DEFAULT now(),",
    "FOREIGN KEY(backend_id) REFERENCES data_backends(id) ON DELETE CASCADE, UNIQUE(backend_id,environment,role)",
    ");",
    "CREATE TABLE data_backend_environments (",
    "id text PRIMARY KEY, workspace_id text NOT NULL, company_id text NOT NULL, backend_id text NOT NULL,",
    "environment text NOT NULL CHECK(environment IN ('dev','prod')),",
    "provider_config jsonb NOT NULL DEFAULT '{}'::jsonb,",
    "migrator_secret_ref text, runtime_secret_ref text, signing_key_ref text,",
    "status text NOT NULL DEFAULT 'provisioning' CHECK(status IN ('provisioning','ready','unavailable','archived')),",
    "schema_fingerprint text, sync_status text NOT NULL DEFAULT 'synced' CHECK(sync_status IN ('synced','drift_detected','reconciliation_required')),",
    "created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),",
    "UNIQUE(backend_id,environment), UNIQUE(workspace_id,company_id,backend_id,environment),",
    "FOREIGN KEY(workspace_id,company_id,backend_id) REFERENCES data_backends(workspace_id,company_id,id) ON DELETE CASCADE",
    ");",
    "CREATE TABLE data_backend_migrations (",
    "id text PRIMARY KEY, backend_id text NOT NULL, environment text NOT NULL, version bigint NOT NULL,",
    "operation jsonb NOT NULL, reversible boolean NOT NULL, destructive boolean NOT NULL, requires_snapshot boolean NOT NULL,",
    "up_sql text NOT NULL, down_sql text, author_id text NOT NULL, run_id text, checksum text NOT NULL,",
    "status text NOT NULL CHECK(status IN ('pending','applied','failed','rolled_back')), snapshot_ref text,",
    "created_at timestamptz NOT NULL DEFAULT now(), applied_at timestamptz,",
    "FOREIGN KEY(backend_id,environment) REFERENCES data_backend_environments(backend_id,environment) ON DELETE CASCADE",
    ");",
    "CREATE UNIQUE INDEX data_backend_applied_version_idx ON data_backend_migrations(backend_id,environment,version) WHERE status='applied';",
    "CREATE TABLE data_backend_migration_locks (",
    "backend_id text NOT NULL, environment text NOT NULL, owner_token text NOT NULL, expires_at timestamptz NOT NULL,",
    "PRIMARY KEY(backend_id,environment),",
    "FOREIGN KEY(backend_id,environment) REFERENCES data_backend_environments(backend_id,environment) ON DELETE CASCADE",
    ");",
    "CREATE TABLE data_backend_snapshots (",
    "id text PRIMARY KEY, backend_id text NOT NULL, environment text NOT NULL, file_path text NOT NULL,",
    "created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL",
    ");",
    "CREATE TABLE data_backend_ui_metadata (",
    "backend_id text NOT NULL, environment text NOT NULL, object_kind text NOT NULL, object_name text NOT NULL,",
    "display_label text, sort_order integer NOT NULL DEFAULT 0, metadata jsonb NOT NULL DEFAULT '{}'::jsonb,",
    "PRIMARY KEY(backend_id,environment,object_kind,object_name),",
    "FOREIGN KEY(backend_id,environment) REFERENCES data_backend_environments(backend_id,environment) ON DELETE CASCADE",
    ");",
    "CREATE TABLE data_backend_access_policies (",
    "id text PRIMARY KEY, backend_id text NOT NULL, environment text NOT NULL, collection_name text NOT NULL,",
    "policy_json jsonb NOT NULL, version integer NOT NULL DEFAULT 1, updated_at timestamptz NOT NULL DEFAULT now(),",
    "FOREIGN KEY(backend_id,environment) REFERENCES data_backend_environments(backend_id,environment) ON DELETE CASCADE",
    ");",
    "ALTER TABLE projects ADD COLUMN data_backend_id text;",
    "ALTER TABLE projects ADD CONSTRAINT projects_data_backend_fk",
    "FOREIGN KEY(workspace_id,company_id,data_backend_id) REFERENCES data_backends(workspace_id,company_id,id) ON DELETE SET NULL (data_backend_id);",
    "CREATE INDEX projects_data_backend_idx ON projects(workspace_id,company_id,data_backend_id);",
  ].join("\n"));
}
