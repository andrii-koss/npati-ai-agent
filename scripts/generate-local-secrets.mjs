#!/usr/bin/env node
/**
 * Adds every secret docker-compose.yml requires to .env when it is missing (or still a publicly known default),
 * with a fresh random value. Existing safe values are never changed and no value is ever printed.
 *
 *   node scripts/generate-local-secrets.mjs            # write missing secrets into ./.env
 *   node scripts/generate-local-secrets.mjs --check    # only report which secrets are missing or unsafe
 *
 * Security audit 2026-11-24 (C1): compose used to fall back to secrets committed in this repository.
 *
 * Existing installation? Two values are bound to data that already exists:
 *  - NPATI_ENCRYPTION_KEY: when it is replaced, the old key is kept in NPATI_ENCRYPTION_KEY_PREVIOUS (decrypt-only)
 *    until `npx tsx scripts/reencrypt-vault-secrets.ts` has rewritten the stored ciphertext.
 *  - NPATI_POSTGRES_PASSWORD / NPATI_PROJECTS_POSTGRES_ADMIN_PASSWORD / MINIO_ROOT_PASSWORD: Postgres applies
 *    POSTGRES_PASSWORD only when the volume is created. Rotate the role password too (see docker/README.md).
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";

const ENV_PATH = path.resolve(process.argv.find((arg) => arg.startsWith("--env="))?.slice(6) ?? ".env");
const CHECK_ONLY = process.argv.includes("--check");

const LEGACY_ENCRYPTION_DEFAULT = "npati-local-development-encryption-key-change-before-production";
const insecure = (value) => !value || /^npati-local-|^npati-development-|change-before-production|change-me|^npati-agent-internal-local$|^replace[-_ ]?with|^your[-_]/i.test(value)
  || ["npati", "postgres", "password", "admin", "minioadmin", "changeme", "secret"].includes(value.toLowerCase());

/** name → bytes of randomness (hex encoded, so URL- and shell-safe). */
const SECRETS = {
  NPATI_ENCRYPTION_KEY: 32,
  NPATI_REMOTE_ACCESS_TOKEN_SECRET: 32,
  // NPATI_JWT_SECRET is deliberately absent: when set it must equal the NPATI backend's signing secret, and when empty
  // sessions are verified by the backend itself. A generated value would reject every real session.
  NPATI_PREVIEW_SECRET: 32,
  NPATI_PRODUCTION_TOKEN: 32,
  NPATI_SANDBOX_RUNNER_SECRET: 32,
  NPATI_BROWSER_INTERNAL_TOKEN: 32,
  CRAWL4AI_API_TOKEN: 24,
  CRAWL4AI_SECRET_KEY: 24,
  OMNIROUTE_API_KEY: 24,
  OMNIROUTE_MANAGEMENT_PASSWORD: 24,
  NPATI_SEARXNG_SECRET: 24,
  NPATI_REDIS_PASSWORD: 24,
  NPATI_POSTGRES_PASSWORD: 24,
  NPATI_PROJECTS_POSTGRES_ADMIN_PASSWORD: 24,
  MINIO_ROOT_PASSWORD: 24,
};

const source = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : "";
const current = new Map();
for (const line of source.split(/\r?\n/)) {
  const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
  if (match) current.set(match[1], match[2].replace(/^(["'])(.*)\1$/, "$2"));
}

const changes = [];
for (const [name, bytes] of Object.entries(SECRETS)) {
  const value = current.get(name);
  if (value && !insecure(value)) continue;
  changes.push({ name, reason: value ? "publicly known default" : "missing", value: randomBytes(bytes).toString("hex") });
}

if (!changes.length) {
  console.log("All compose secrets are set and none is a known default.");
  process.exit(0);
}
for (const change of changes) console.log(`${CHECK_ONLY ? "needs" : "generated"} ${change.name} (${change.reason})`);
if (CHECK_ONLY) process.exit(1);

const lines = source.split(/\r?\n/);
const extra = [];
const encryptionChange = changes.find((change) => change.name === "NPATI_ENCRYPTION_KEY");
if (encryptionChange && !current.has("NPATI_ENCRYPTION_KEY_PREVIOUS")) {
  // Data written by an earlier start used the old (possibly compose default) key; keep it readable, decrypt-only.
  extra.push(`NPATI_ENCRYPTION_KEY_PREVIOUS=${current.get("NPATI_ENCRYPTION_KEY") || LEGACY_ENCRYPTION_DEFAULT}`);
  console.log("kept the previous encryption key as NPATI_ENCRYPTION_KEY_PREVIOUS (decrypt-only); run scripts/reencrypt-vault-secrets.ts, then remove it");
}
for (const change of changes) {
  const index = lines.findIndex((line) => new RegExp(`^\\s*${change.name}\\s*=`).test(line));
  if (index >= 0) lines[index] = `${change.name}=${change.value}`;
  else extra.push(`${change.name}=${change.value}`);
}
if (existsSync(ENV_PATH)) copyFileSync(ENV_PATH, `${ENV_PATH}.bak-${Date.now()}`);
const body = lines.join("\n").replace(/\n*$/, "\n");
writeFileSync(ENV_PATH, extra.length ? `${body}\n# Generated by scripts/generate-local-secrets.mjs (${new Date().toISOString().slice(0, 10)})\n${extra.join("\n")}\n` : body, { mode: 0o600 });
console.log(`Updated ${ENV_PATH} (backup written next to it).`);
if (changes.some((change) => ["NPATI_POSTGRES_PASSWORD", "NPATI_PROJECTS_POSTGRES_ADMIN_PASSWORD", "MINIO_ROOT_PASSWORD"].includes(change.name)) && /POSTGRES|MINIO/.test(source)) {
  console.log("Existing volumes keep their old database/storage passwords: rotate them as described in docker/README.md.");
}
