const DICTS: Partial<Record<SupportedLanguage, Record<string, string>>> = {
  uk: PROVIDER_DESCRIPTIONS_UK,
  pl: PROVIDER_DESCRIPTIONS_PL,
  de: PROVIDER_DESCRIPTIONS_DE,
  fr: PROVIDER_DESCRIPTIONS_FR,
  es: PROVIDER_DESCRIPTIONS_ES,
  it: PROVIDER_DESCRIPTIONS_IT,
};

export function getLocalizedProviderDescription(
  provider: { id: string; name: string; description?: string; authHint?: string },
  t: (key: any) => string,
  language: SupportedLanguage
): string {
  const id = provider.id.toLowerCase();

  // 1. Direct language catalog lookup
  const langDict = DICTS[language];
  if (langDict && langDict[id]) {
    return langDict[id];
  }

  // 2. Specific key in i18n locale schema
  const localizedKey = `aiMarketplace.providers.${id}.desc`;
  const val = t(localizedKey as any);
  if (val && val !== localizedKey) {
    return val;
  }

  // 3. Fallback for non-English languages: NEVER show raw untranslated English sentences
  const defaultFallback = t("aiMarketplace.cards.defaultProviderDesc");

  if (!provider.description && !provider.authHint) {
    return defaultFallback;
  }

  const raw = (provider.description || "").replaceAll("OmniRoute", "Npati").trim();
  if (
    !raw ||
    raw === "AI provider available through the Npati registry." ||
    raw === "AI provider available through the OmniRoute registry." ||
    raw === "AI provider available through the Npati registry"
  ) {
    return defaultFallback;
  }

  // For non-English languages, if we couldn't find an exact translation for a custom description,
  // use the localized default fallback instead of leaking English sentences.
  if (language !== "en") {
    return defaultFallback;
  }

  return raw;
}
