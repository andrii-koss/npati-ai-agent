import { createHash } from "node:crypto";
import { scanTextForSecrets } from "./code-secret-scanner";
import { redactLeaseValues } from "./code-secret-lease";
import { estimateMessagesTokens, estimateContextTokens } from "./code-context-budget";

/**
 * C8 — conversation compaction for long code runs.
 *
 * Two mechanisms, on purpose kept apart:
 *
 *   1. **Stub replacement.** Old tool results are replaced by a short, structured stub. The call itself is
 *      preserved (tool call id, tool name, schema version, argument hash, outcome), because requirement 4 says
 *      the calls survive the elision: a transcript whose calls vanished can no longer explain what the agent
 *      did, which is the whole point of keeping it. Only the payload is dropped, and it is dropped
 *      **wholesale** — never half-mangled.
 *   2. **Structured summary.** Goal, decisions, changed files, executed commands with their results, open
 *      problems and next steps, plus the last N turns verbatim.
 *
 * Why the summary is extracted by rules rather than generated by a model: compaction changes the input the
 * model sees, so it must be a **function of that input** to stay compatible with deterministic replay (C6b).
 * An LLM-written summary would differ between two replays of the same run, and the replay would diverge for a
 * reason that has nothing to do with the agent. Rule extraction is less fluent and it is reproducible — for
 * this purpose the second property is the one that matters, and the fluent alternative is left as a recorded
 * artifact outside `replayInput` if it is ever wanted.
 *
 * Lossy text compression is deliberately **not** applied to code, diffs, patch bodies or fenced blocks. The
 * existing `code-safe` preset already protects them; this module does not even attempt in-place rewriting, so
 * there is nothing to get wrong: content is either kept byte-for-byte or replaced entirely by a stub.
 */

export const COMPACTION_SCHEMA_VERSION = 1;

/** Turns that are never touched: the model needs recent context verbatim to continue coherently. */
export const DEFAULT_KEEP_RECENT_TURNS = 4;

/** Bounds of the persisted summary; a summary larger than this is truncated with an explicit marker. */
export const MAX_SUMMARY_CHARS = 8_000;

export const STUB_MARKER = "[tool result elided by context compaction]";

export interface CompactableMessage {
  role: string;
  content: string;
  /** Present on tool-result messages; preserved by the stub so the call remains legible. */
  toolCallId?: string;
  toolName?: string;
  toolVersion?: number;
  argumentsHash?: string;
  outcome?: string;
}

export interface CompactionSummary {
  schemaVersion: number;
  goal: string;
  decisions: string[];
  changedFiles: string[];
  commands: Array<{ command: string; result: string }>;
  openProblems: string[];
  nextSteps: string[];
  truncated: boolean;
  contentHash: `sha256:${string}`;
}

export interface CompactionInput {
  messages: readonly CompactableMessage[];
  keepRecentTurns?: number;
  maxSummaryChars?: number;
  /**
   * Keep everything from the N-th last assistant message on, so a turn's parallel tool results are never split.
   * Counted in turns rather than messages: six reads of one turn are seven messages, and `keepRecentTurns: 4`
   * used to stub the current turn's own reads (audit F-01).
   */
  keepRecentAssistantTurns?: number;
  /**
   * Never stub the latest `code.fs.read` result of a file that was not written afterwards, up to this many
   * characters in total. Stubbing those made the model re-read the same files every few turns (audit F-01: 71
   * turns, 112 reads, 0 edits).
   */
  preserveLatestReadsChars?: number;
}

export interface CompactionResult {
  messages: CompactableMessage[];
  summary: CompactionSummary;
  /**
   * C8 (owner decision): the artifact **is** the model-visible state of this compaction. Deterministic replay
   * must feed the exact recorded artifact and must not re-run a summarizer, because a regenerated summary can
   * differ and the replay would then diverge for a reason that has nothing to do with the agent.
   */
  artifact: CompressionArtifact;
  /** Number of tool results replaced by stubs. */
  stubbed: number;
  tokensBefore: number;
  tokensAfter: number;
  /** Hash of the compacted message list: the exact input the next model call receives. */
  contentHash: `sha256:${string}`;
}

/**
 * The recorded, replayable description of one compaction.
 *
 * Everything needed to reconstruct the model-visible context without recomputing anything lives here: which
 * turns were summarised (`sourceTurnRange` plus their hashes), which turns were kept verbatim (`retainedTurnIds`),
 * which tool results were pruned (as references, not payloads), the placeholders the model actually saw, and
 * the hash of the whole thing. `pinnedEvidence` records what was deliberately excluded from compaction.
 */
export interface CompressionArtifact {
  schemaVersion: number;
  sourceTurnRange: { from: number; to: number };
  sourceHashes: string[];
  /** The exact generated summary text, as shown to the model. */
  summaryText: string;
  retainedTurnIds: string[];
  prunedToolResultRefs: Array<{
    turnIndex: number;
    toolCallId?: string;
    toolName?: string;
    argumentsHash?: string;
    outcome?: string;
    chars: number;
  }>;
  modelVisiblePlaceholders: string[];
  /** Evidence that is never compressed, regardless of size. */
  pinnedEvidence: {
    goal: string;
    decisions: string[];
    plan: string[];
    currentDiff: string[];
    currentFiles: string[];
    unresolvedErrors: string[];
    latestResults: string[];
  };
  contentHash: `sha256:${string}`;
}

/**
 * Pinned evidence: the boundary the owner drew is not "code vs prose" but **"current and decisive" vs "old and
 * reproducible"**. A current diff, the plan, an unresolved error or the latest test result is what the agent is
 * working from right now, and compressing it away is what makes a compacted session lose the thread. Old tool
 * output, by contrast, is reproducible by re-running the call, so it becomes a bounded placeholder plus a
 * reference while the call itself stays in the transcript.
 */
export const PINNED_EVIDENCE_SCHEMA_VERSION = 1;

const CURRENT_DIFF_PATTERN = /^(?:\*\*\* (?:Update|Add) File:|\+\+\+ b\/|--- a\/|diff --git |@@ )/;
// "Open problem" belongs here: the owner listed unresolved errors as pinned evidence, and a stated open
// problem is exactly that — an unresolved issue the agent must not lose when old output is pruned.
const UNRESOLVED_ERROR_PATTERN = /(?:^|\s)(?:error|failed|FAIL|Traceback|exception|unresolved|open problem|blocker|blocked)(?::|\s|$)/i;
const LATEST_RESULT_PATTERN = /(?:tests? passed|tests? failed|\d+ passing|\d+ failing|exit code \d+|build succeeded)/i;
const PLAN_PATTERN = /^(?:[-*]\s*)?(?:plan|todo|step \d+|\d+\.)\b[:\s]/i;

/**
 * A summary is stored as a session artifact and, like every other write in this project, it must not carry a
 * secret. It is refused loudly rather than scrubbed: silently removing the value would hide the leak from
 * whoever produced it, and the same value is already sitting one message away.
 */
export class ContextSummarySecretError extends Error {
  readonly code = "context_summary_secret_detected";
  readonly httpStatus = 403;
  readonly retryable = false;
  readonly findings: Array<{ kind: string; line: number }>;

  constructor(findings: Array<{ kind: string; line: number }>) {
    super("context summary rejected: it contains what looks like a secret");
    this.name = "ContextSummarySecretError";
    this.findings = findings;
  }
}

function sha256(value: string): `sha256:${string}` {
  return `sha256:${createHash("sha256").update(value, "utf8").digest("hex")}`;
}

function firstLine(text: string, limit = 240): string {
  const line = text.split(/\r?\n/).find((candidate) => candidate.trim().length > 0) ?? "";
  return line.trim().slice(0, limit);
}

function matchingLines(text: string, pattern: RegExp, limit: number): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.length === 0 || !pattern.test(line)) continue;
    const normalized = line.slice(0, 300);
    if (seen.has(normalized)) continue;
    seen.add(normalized);
    out.push(normalized);
    if (out.length >= limit) break;
  }
  return out;
}

const DECISION_PATTERN = /^(?:[-*]\s*)?(?:decision|decided|chose|approach|we will|will use|plan)\b[:\s]/i;
const PROBLEM_PATTERN = /^(?:[-*]\s*)?(?:open problem|problem|blocked|blocker|unresolved|failed|error|todo|fixme)\b[:\s]/i;
const NEXT_STEP_PATTERN = /^(?:[-*]\s*)?(?:next step|next|then|follow[- ]?up|remaining)\b[:\s]/i;
const CHANGED_FILE_PATTERN = /^(?:\*\*\* (?:Update|Add) File:|\+\+\+ b\/|--- a\/|diff --git )\s*(.+)$/;

function collectChangedFiles(texts: readonly string[], limit: number): string[] {
  const files = new Set<string>();
  for (const text of texts) {
    for (const raw of text.split(/\r?\n/)) {
      const match = CHANGED_FILE_PATTERN.exec(raw.trim());
      if (!match) continue;
      const path = (match[1] ?? "").trim();
      if (path.length > 0) files.add(path.slice(0, 300));
      if (files.size >= limit) return [...files];
    }
  }
  return [...files];
}

/**
 * Extracts the structured summary. Order of the input is the only ordering input, so the same message list
 * always produces the same summary, byte for byte.
 */
export function summarizeConversation(input: {
  messages: readonly CompactableMessage[];
  maxSummaryChars?: number;
}): CompactionSummary {
  const maxSummaryChars = input.maxSummaryChars ?? MAX_SUMMARY_CHARS;
  const userMessages = input.messages.filter((message) => message.role === "user");
  const assistantMessages = input.messages.filter((message) => message.role === "assistant");
  const toolMessages = input.messages.filter((message) => message.role === "tool");
  const allTexts = input.messages.map((message) => message.content);

  const goal = firstLine(userMessages[0]?.content ?? "");
  const decisions = matchingLines(assistantMessages.map((m) => m.content).join("\n"), DECISION_PATTERN, 12);
  const changedFiles = collectChangedFiles(allTexts, 40);
  const commands = toolMessages
    .filter((message) => message.toolName === "code.shell.run" || message.toolName === "code.verify.run")
    .slice(-20)
    .map((message) => ({
      command: message.argumentsHash ? `${message.toolName ?? "tool"} (args ${message.argumentsHash})` : message.toolName ?? "tool",
      // The result is bounded here too: a summary is an index, not a second copy of the transcript.
      result: (message.content ?? "").slice(0, 400),
    }));
  const openProblems = matchingLines(assistantMessages.map((m) => m.content).join("\n"), PROBLEM_PATTERN, 12);
  const nextSteps = matchingLines(
    [...assistantMessages].reverse().map((m) => m.content).join("\n"),
    NEXT_STEP_PATTERN,
    10,
  );

  const body = { goal, decisions, changedFiles, commands, openProblems, nextSteps };
  const serialised = JSON.stringify(body);
  const truncated = serialised.length > maxSummaryChars;

  const summary: CompactionSummary = {
    schemaVersion: COMPACTION_SCHEMA_VERSION,
    goal: goal.slice(0, 500),
    decisions,
    changedFiles,
    commands,
    openProblems,
    nextSteps,
    truncated,
    contentHash: sha256(serialised.slice(0, maxSummaryChars)),
  };
  return summary;
}

/** Refuses (never scrubs) a summary that carries a secret; data classification is the caller's job. */
export function assertNoSecretsInSummary(summary: CompactionSummary): void {
  const scan = scanTextForSecrets(JSON.stringify(summary));
  if (scan.findings.length > 0) {
    throw new ContextSummarySecretError(
      scan.findings.map((finding) => ({ kind: finding.kind, line: finding.line })),
    );
  }
}

/**
 * Refuses a summary text that contains the value of a **SecretLease** issued to this session.
 *
 * A lease value is opaque by construction, so no pattern scanner can recognise it — which is exactly why the
 * check has to be "compare against the values we know we issued" rather than another regex. It reuses
 * `redactLeaseValues`, the helper the shell path already uses to strip lease values from command output, so
 * there is one definition of "this text contains a lease value" in the codebase.
 */
export function assertNoLeaseValuesInSummary(text: string, values: readonly string[]): void {
  const usable = values.filter((value) => typeof value === "string" && value.length >= 6);
  if (usable.length === 0) return;
  if (redactLeaseValues(text, [...usable]) !== text) {
    throw new ContextSummarySecretError([{ kind: "secret_lease", line: 0 }]);
  }
}

function stubFor(message: CompactableMessage): string {
  const identity = [
    message.toolName ? `tool=${message.toolName}` : undefined,
    message.toolVersion !== undefined ? `v${message.toolVersion}` : undefined,
    message.toolCallId ? `call=${message.toolCallId}` : undefined,
    message.argumentsHash ? `args=${message.argumentsHash}` : undefined,
    message.outcome ? `outcome=${message.outcome}` : undefined,
  ].filter((part): part is string => Boolean(part));
  const size = estimateContextTokens(message.content) * 4;
  return `${STUB_MARKER} ${identity.join(" ")} chars=${size}`;
}

const WRITE_RESULT_TOOLS = /^code.fs.(write|edit|apply_patch|move|delete)$/;

function toolResultPaths(content: string): string[] {
  try {
    const value = JSON.parse(content) as { ok?: boolean; result?: { data?: Record<string, unknown> } & Record<string, unknown> };
    if (value.ok !== true) return [];
    const data = (value.result?.data ?? value.result ?? {}) as Record<string, unknown>;
    const rows = Array.isArray(data.files) ? data.files as Array<Record<string, unknown>> : [data];
    return rows.flatMap((row) => [row.path, row.from, row.to]).filter((path): path is string => typeof path === "string");
  } catch {
    return [];
  }
}

/**
 * Indices of the newest successful `code.fs.read` result per path that no later write touched, newest first, while
 * their total size in the compacted region stays within `budgetChars`. Deterministic: depends only on the message list.
 */
function latestUnchangedReads(messages: readonly CompactableMessage[], budgetChars: number, elidableEnd: number): Set<number> {
  const keep = new Set<number>();
  const written = new Set<string>();
  const seen = new Set<string>();
  let used = 0;
  for (let index = messages.length - 1; index >= 0; index -= 1) {
    const message = messages[index]!;
    if (message.role !== "tool" || message.content.startsWith(STUB_MARKER)) continue;
    if (message.toolName && WRITE_RESULT_TOOLS.test(message.toolName)) {
      for (const path of toolResultPaths(message.content)) written.add(path);
      continue;
    }
    if (message.toolName !== "code.fs.read") continue;
    const [path] = toolResultPaths(message.content);
    if (!path || written.has(path) || seen.has(path)) continue;
    seen.add(path);
    // Reads in the kept tail are kept anyway: they only mark the path as already visible, never use the budget.
    if (index >= elidableEnd || used + message.content.length > budgetChars) continue;
    used += message.content.length;
    keep.add(index);
  }
  return keep;
}

/**
 * Compacts a conversation. Deterministic: the same input always yields byte-identical output, which is what
 * lets the compacted list be part of the replayed input rather than an out-of-band artifact.
 */
export function compactConversation(input: CompactionInput): CompactionResult {
  const keepRecentTurns = Math.max(0, input.keepRecentTurns ?? DEFAULT_KEEP_RECENT_TURNS);
  const messages = input.messages;
  const tokensBefore = estimateMessagesTokens(messages);

  // The system message and the original goal are never elided: losing them would lose the task itself.
  const protectedCount = Math.min(messages.length, 2);
  let elidableEnd = Math.max(protectedCount, messages.length - keepRecentTurns);
  if (input.keepRecentAssistantTurns !== undefined && input.keepRecentAssistantTurns > 0) {
    const assistants = messages.map((message, index) => (message.role === "assistant" ? index : -1)).filter((index) => index >= 0);
    const boundary = assistants[assistants.length - input.keepRecentAssistantTurns];
    if (boundary !== undefined) elidableEnd = Math.max(protectedCount, Math.min(elidableEnd, boundary));
  }
  const preserved = input.preserveLatestReadsChars ? latestUnchangedReads(messages, input.preserveLatestReadsChars, elidableEnd) : new Set<number>();
  let stubbed = 0;

  const compacted = messages.map((message, index) => {
    const elidable = index >= protectedCount && index < elidableEnd && !preserved.has(index);
    if (!elidable) return message;
    if (message.role !== "tool" || message.content.startsWith(STUB_MARKER) || stubFor(message).length >= message.content.length) return message;
    stubbed += 1;
    return {
      ...message,
      content: stubFor(message),
    };
  });

  const summary = summarizeConversation({
    messages,
    ...(input.maxSummaryChars !== undefined ? { maxSummaryChars: input.maxSummaryChars } : {}),
  });
  assertNoSecretsInSummary(summary);

  const tokensAfter = estimateMessagesTokens(compacted);
  const artifact = buildCompressionArtifact({
    original: messages,
    compacted,
    summary,
    stubbedFrom: protectedCount,
    stubbedTo: elidableEnd,
  });

  return {
    messages: compacted,
    summary,
    artifact,
    stubbed,
    tokensBefore,
    tokensAfter,
    contentHash: sha256(compacted.map((message) => `${message.role}\u0000${message.content}`).join("\u0001")),
  };
}

/**
 * Collects the evidence that is never compressed: what the agent is working from right now. The boundary is
 * "current and decisive" versus "old and reproducible" — not "code versus prose" — because a current diff or
 * an unresolved error is exactly what a compacted session must not lose, while an old tool output can be
 * reproduced by re-running the call it belongs to.
 */
export function collectPinnedEvidence(messages: readonly CompactableMessage[]): CompressionArtifact["pinnedEvidence"] {
  const assistantText = messages.filter((m) => m.role === "assistant").map((m) => m.content).join("\n");
  const toolText = messages.filter((m) => m.role === "tool").map((m) => m.content).join("\n");
  const allTexts = messages.map((m) => m.content);

  const diffLines: string[] = [];
  for (const text of allTexts) {
    for (const raw of text.split(/\r?\n/)) {
      const line = raw.trimEnd();
      if (line.length === 0 || !CURRENT_DIFF_PATTERN.test(line.trim())) continue;
      diffLines.push(line.slice(0, 400));
      if (diffLines.length >= 80) break;
    }
    if (diffLines.length >= 80) break;
  }

  return {
    goal: firstLine(messages.find((m) => m.role === "user")?.content ?? "", 500),
    decisions: matchingLines(assistantText, DECISION_PATTERN, 20),
    plan: matchingLines(assistantText, PLAN_PATTERN, 20),
    currentDiff: diffLines,
    currentFiles: collectChangedFiles(allTexts, 40),
    unresolvedErrors: matchingLines([assistantText, toolText].join("\n"), UNRESOLVED_ERROR_PATTERN, 20),
    latestResults: matchingLines(toolText, LATEST_RESULT_PATTERN, 10),
  };
}

/**
 * Builds the recorded artifact. It is a pure function of the messages and the summary, so two identical runs
 * produce byte-identical artifacts — which is what lets a replay feed the recorded artifact instead of
 * recomputing a summary that an LLM would produce differently the second time.
 */
export function buildCompressionArtifact(input: {
  original: readonly CompactableMessage[];
  compacted: readonly CompactableMessage[];
  summary: CompactionSummary;
  stubbedFrom: number;
  stubbedTo: number;
}): CompressionArtifact {
  const pruned = input.compacted
    .map((message, index) => ({ message, index }))
    .filter(({ message, index }) =>
      index >= input.stubbedFrom && index < input.stubbedTo && message.content.startsWith(STUB_MARKER))
    .map(({ message, index }) => ({
      turnIndex: index,
      ...(message.toolCallId ? { toolCallId: message.toolCallId } : {}),
      ...(message.toolName ? { toolName: message.toolName } : {}),
      ...(message.argumentsHash ? { argumentsHash: message.argumentsHash } : {}),
      ...(message.outcome ? { outcome: message.outcome } : {}),
      chars: estimateContextTokens(message.content) * 4,
    }));

  const retainedTurnIds = input.compacted
    .map((message, index) => ({ message, index }))
    .filter(({ index }) => index < input.stubbedFrom || index >= input.stubbedTo)
    .map(({ message, index }) => `${index}:${message.role}${message.toolCallId ? `:${message.toolCallId}` : ""}`);

  const summaryText = renderSummaryMessage(input.summary);
  const body = {
    schemaVersion: COMPACTION_SCHEMA_VERSION,
    sourceTurnRange: {
      from: input.stubbedFrom,
      to: Math.max(input.stubbedFrom, input.stubbedTo - 1),
    },
    sourceHashes: input.original
      .slice(input.stubbedFrom, input.stubbedTo)
      .map((message) => sha256(`${message.role}\u0000${message.content}`)),
    summaryText,
    retainedTurnIds,
    prunedToolResultRefs: pruned,
    modelVisiblePlaceholders: input.compacted
      .filter((message) => message.content.startsWith(STUB_MARKER))
      .map((message) => message.content),
    pinnedEvidence: collectPinnedEvidence(input.original),
  };

  return { ...body, contentHash: sha256(JSON.stringify(body)) };
}

/**
 * Turns the summary into the single message that replaces the elided part of the transcript. Kept as text
 * only: it is inserted as data, under the same invariant as everything else the agent reads.
 */
export function renderSummaryMessage(summary: CompactionSummary): string {
  const lines: string[] = [
    `Context summary of the earlier part of this session (schema v${summary.schemaVersion}).`,
    `Goal: ${summary.goal || "(not recorded)"}`,
  ];
  const section = (title: string, values: readonly string[]): void => {
    if (values.length === 0) return;
    lines.push(`${title}:`);
    for (const value of values) lines.push(`- ${value}`);
  };
  section("Decisions", summary.decisions);
  section("Changed files", summary.changedFiles);
  if (summary.commands.length > 0) {
    lines.push("Executed commands:");
    for (const command of summary.commands) lines.push(`- ${command.command} -> ${command.result}`);
  }
  section("Open problems", summary.openProblems);
  section("Next steps", summary.nextSteps);
  if (summary.truncated) lines.push("(summary truncated to its configured size limit)");
  return lines.join("\n");
}
