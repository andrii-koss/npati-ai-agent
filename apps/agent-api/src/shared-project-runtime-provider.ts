import { randomUUID } from "node:crypto";
import { spawn, execFile, type ChildProcess } from "node:child_process";
import { promisify } from "node:util";
import { chown, chmod, mkdir, readFile, writeFile, rename, rm, open } from "node:fs/promises";
import path from "node:path";
import {
  SandboxProviderError, sandboxProcessEnvironment, type SandboxProvider, type SandboxScope,
  type SandboxStatus, type SandboxCreateOptions, type SandboxCommandOptions, type SandboxCommandResult,
  type SandboxFile, type PreviewProxyRequest, type PreviewProxyResponse,
} from "./sandbox-provider";
import { normalizeTerminalCommand, classifyTerminalCommand } from "./terminal-command-policy";
import { safeProjectPath } from "./project-workspace";
import { gitShellHardeningEnv, resolveDepsPolicyLimits } from "./code-deps-policy";

type ProcessRecord = { id: string; pid?: number; status: SandboxCommandResult["status"]; exitCode: number | null };
type Entry = SandboxStatus & { scope: SandboxScope; uid: number; port: number; processes: Record<string, ProcessRecord> };
const UUID = /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i;
const scopeKey = (scope: SandboxScope) => JSON.stringify([scope.workspaceId, scope.userId, scope.companyId, scope.projectId]);
const excluded = /^(?:node_modules|\.git|\.next|dist|build|coverage|\.expo|\.npati-runtime|\.worktrees)$/;
const executeFile = promisify(execFile);

/** Preview commands are generated by the existing stack detector. Only replace
 * the server port argument; other commands still go through terminal policy. */
export function projectRuntimeCommandPort(command: string, port: number): string {
  if (/\s(?:--port(?:=|\s)|-[pl]\s)\d+\b/.test(command)) return command.replace(/(\s(?:--port(?:=|\s)|-[pl]\s))\d+\b/g, `$1${port}`);
  if (/^python3? -m http\.server \d+$/.test(command)) return command.replace(/\d+$/, String(port));
  if (/^php -S (?:127\.0\.0\.1|0\.0\.0\.0):\d+$/.test(command)) return command.replace(/:\d+$/, `:${port}`);
  if (/^(?:npm|pnpm|yarn)\s+(?:run\s+)?(?:dev|start|preview)\b/.test(command)) return `${command}${/\s--(?:\s|$)/.test(command) ? "" : " --"} --port ${port}`;
  if (/^(?:npx\s+(?:--yes\s+)?|npm\s+exec\s+--\s+)?(?:next|vite|expo|astro|nuxt)\b/.test(command)) return `${command} --port ${port}`;
  return command; // Node servers receive PORT in their project-only environment.
}

export function projectRuntimeWorkspaceCommand(command: string, directory: string): string {
  return command.replace(/\/workspace(?=\/|\s|['"]|$)/g, directory);
}

/** One supervisor, many logical sandboxes. It implements the existing contract,
 * so canonical file revisions, project context, approvals and audit stay in API. */
export class SharedProjectRuntimeProvider implements SandboxProvider {
  private entries: Entry[] = [];
  private ready: Promise<void>;
  private saving: Promise<void> = Promise.resolve();
  private children = new Map<string, ChildProcess>();
  private jobs = new Map<string, Set<ChildProcess>>();
  constructor(private readonly root = "/projects", private readonly state = "/runtime-state", private readonly launcher = "/usr/local/bin/npati-project-exec") {
    this.ready = this.initialize();
  }
  private async initialize() {
    await mkdir(this.root, { recursive: true, mode: 0o711 });
    await mkdir(this.state, { recursive: true, mode: 0o700 });
    await chmod(this.state, 0o700);
    try { this.entries = JSON.parse(await readFile(path.join(this.state, "projects.json"), "utf8")); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
    // Container restart kills all project children. Never trust persisted PIDs.
    for (const entry of this.entries) for (const process of Object.values(entry.processes)) if (process.status === "running") { process.status = "stopped"; process.pid = undefined; }
  }
  private persist() {
    this.saving = this.saving.catch(() => undefined).then(async () => {
      const file = path.join(this.state, "projects.json"), temporary = `${file}.tmp`;
      await writeFile(temporary, JSON.stringify(this.entries), { mode: 0o600 });
      await rename(temporary, file);
    });
    return this.saving;
  }
  private async entry(scope: SandboxScope, id: string) {
    await this.ready;
    const entry = this.entries.find(item => item.id === id);
    if (!entry) throw new SandboxProviderError("sandbox_not_found", "Project runtime workspace not found", 404);
    if (scopeKey(entry.scope) !== scopeKey(scope)) throw new SandboxProviderError("scope_mismatch", "Runtime workspace belongs to another Project context", 403);
    entry.lastActivityAt = new Date().toISOString();
    return entry;
  }
  private directory(entry: Entry) { return path.join(this.root, entry.scope.projectId); }
  private status(entry: Entry): SandboxStatus { return { id: entry.id, state: entry.state, createdAt: entry.createdAt, lastActivityAt: entry.lastActivityAt }; }
  async createSandbox(scope: SandboxScope, options: SandboxCreateOptions = {}) {
    await this.ready;
    if (!UUID.test(scope.projectId) || !scope.workspaceId || !scope.userId || !scope.companyId) throw new SandboxProviderError("invalid_scope", "Invalid Project context", 400);
    // Host-folder mounts retain the existing isolated Docker path; they cannot be
    // expanded into this shared container by an API caller.
    if (options.mount) throw new SandboxProviderError("shared_runtime_mount_unsupported", "Shared runtime accepts NPATI workspaces; use the isolated runner for host-folder mounts", 403);
    const existing = this.entries.find(item => item.scope.projectId === scope.projectId);
    if (existing) { await this.entry(scope, existing.id); return this.status(existing); }
    let uid = 10000;
    while (this.entries.some(item => item.uid === uid)) uid++;
    let port = 3001;
    while (this.entries.some(item => item.port === port) || [7865, 8080].includes(port)) port++;
    if (uid > 60000 || port > 65000) throw new SandboxProviderError("runtime_capacity", "Shared runtime capacity reached", 429);
    const now = new Date().toISOString();
    const entry: Entry = { id: randomUUID(), scope: { ...scope }, uid, port, state: "created", createdAt: now, lastActivityAt: now, processes: {} };
    // Reserve identity synchronously before any I/O (concurrent requests cannot
    // assign the same UID/port).
    this.entries.push(entry);
    try {
      const directory = this.directory(entry);
      await mkdir(directory, { mode: 0o700 });
      await chown(directory, uid, uid);
      for (const name of [".npati-runtime", ".npati-runtime/tmp", ".npati-runtime/home"]) {
        const target = path.join(directory, name); await mkdir(target, { recursive: true, mode: 0o700 }); await chown(target, uid, uid);
      }
      await this.persist();
    } catch (error) { this.entries = this.entries.filter(item => item !== entry); throw error; }
    return this.status(entry);
  }
  async startSandbox(scope: SandboxScope, id: string) { const entry = await this.entry(scope, id); entry.state = "running"; await this.persist(); return this.status(entry); }
  async stopSandbox(scope: SandboxScope, id: string) {
    const entry = await this.entry(scope, id);
    for (const child of this.jobs.get(id) ?? []) if (child.pid) { try { process.kill(-child.pid, "SIGKILL"); } catch { /* finished */ } }
    for (const process of Object.values(entry.processes)) if (process.status === "running") await this.stopProcess(scope, id, process.id);
    // Include descendants that detached themselves from the original process
    // group; no process of a different project shares this UID.
    await executeFile("pkill", ["-KILL", "-u", String(entry.uid)]).catch((error: { code?: number }) => { if (error.code !== 1) throw error; });
    entry.state = "stopped"; await this.persist(); return this.status(entry);
  }
  async destroySandbox(scope: SandboxScope, id: string) {
    const entry = await this.entry(scope, id);
    await this.stopSandbox(scope, id);
    for (const processId of Object.keys(entry.processes)) await rm(path.join(this.state, `${processId}.log`), { force: true });
    await rm(this.directory(entry), { recursive: true, force: true });
    this.entries = this.entries.filter(item => item !== entry); await this.persist();
  }
  async getStatus(scope: SandboxScope, id: string) { return this.status(await this.entry(scope, id)); }
  private environment(entry: Entry, environment: Record<string, string> = {}) {
    if (Object.entries(environment).some(([key, value]) => !/^[A-Z_][A-Z0-9_]{0,63}$/.test(key) || typeof value !== "string" || value.length > 16384)) throw new SandboxProviderError("invalid_environment", "Invalid project environment", 400);
    const directory = this.directory(entry);
    // Never inherit supervisor credentials or user-controlled runtime loader paths.
    // Foreground requests may contain an explicitly approved, temporary Git
    // credential config (repository import). Preserve that trusted API config;
    // normal terminal calls already receive Git hardening from the API.
    const projectEnvironment = Object.fromEntries(Object.entries(environment).map(([key, value]) => [key, value.startsWith("/workspace") ? projectRuntimeWorkspaceCommand(value, directory) : value]));
    return { ...gitShellHardeningEnv(resolveDepsPolicyLimits()), ...projectEnvironment,
      PATH: "/opt/npati-package-managers/bin:/usr/local/bin:/usr/bin:/bin", HOME: `${directory}/.npati-runtime/home`, TMPDIR: `${directory}/.npati-runtime/tmp`,
      PORT: String(entry.port), HOST: "0.0.0.0", NODE_OPTIONS: "", NODE_PATH: "", LD_PRELOAD: "", LD_LIBRARY_PATH: "",
      HTTP_PROXY: "http://127.0.0.1:8080", HTTPS_PROXY: "http://127.0.0.1:8080", http_proxy: "http://127.0.0.1:8080", https_proxy: "http://127.0.0.1:8080",
      npm_config_proxy: "http://127.0.0.1:8080", npm_config_https_proxy: "http://127.0.0.1:8080", NPM_CONFIG_CACHE: `${directory}/.npati-runtime/npm`,
      npm_config_audit: "false", npm_config_fund: "false", NEXT_TELEMETRY_DISABLED: "1", CI: "1" };
  }
  private launch(entry: Entry, executable: string, args: string[], cwd = ".", environment?: Record<string, string>, detached = false) {
    return spawn(this.launcher, [String(entry.uid), this.directory(entry), String(entry.port), path.join(this.directory(entry), cwd), executable, ...args],
      { env: this.environment(entry, environment), detached, stdio: ["pipe", "pipe", "pipe"] });
  }
  private async collect(entry: Entry, executable: string, args: string[], input: string, options: SandboxCommandOptions, cwd = ".") {
    const child = this.launch(entry, executable, args, cwd, options.environment, true);
    const jobs = this.jobs.get(entry.id) ?? new Set<ChildProcess>(); this.jobs.set(entry.id, jobs); jobs.add(child);
    const limit = Math.min(Math.max(options.outputLimitBytes, 1024), 32_000_000);
    let stdout = Buffer.alloc(0), stderr = Buffer.alloc(0), timedOut = false;
    const started = Date.now();
    const stop = () => { if (child.pid) { try { process.kill(-child.pid, "SIGKILL"); } catch { /* already exited */ } } };
    const timer = setTimeout(() => { timedOut = true; stop(); }, Math.min(Math.max(options.timeoutMs, 1000), 600_000));
    const done = new Promise<SandboxCommandResult>((resolve, reject) => {
      child.on("error", reject);
      child.stdout!.on("data", (data: Buffer) => { stdout = Buffer.concat([stdout, data]).subarray(0, limit); });
      child.stderr!.on("data", (data: Buffer) => { stderr = Buffer.concat([stderr, data]).subarray(0, limit); });
      child.on("close", code => resolve({ status: timedOut ? "timed_out" : code === 0 ? "completed" : "failed", exitCode: code, stdout: stdout.toString(), stderr: stderr.toString(), durationMs: Date.now() - started, step: "command", tool: "project.terminal.exec", retryable: timedOut }));
    });
    child.stdin!.on("error", () => undefined); child.stdin!.end(input);
    try { return await done; } finally { clearTimeout(timer); stop(); jobs.delete(child); }
  }
  private command(command: string, cwd?: string) { const normalized = normalizeTerminalCommand({ command, cwd }); classifyTerminalCommand({ command: normalized.command, cwd: normalized.cwd }); return normalized; }
  async executeCommand(scope: SandboxScope, id: string, command: string, options: SandboxCommandOptions) {
    const entry = await this.entry(scope, id), normalized = this.command(command, options.cwd);
    if (/^npm (?:install|ci)$/.test(normalized.command) && normalized.cwd === ".") {
      return this.collect(entry, "node", ["/opt/npati-runtime/prepare-project-dependencies.cjs", normalized.command.slice(4)], "", options);
    }
    return this.collect(entry, "sh", ["-s"], projectRuntimeWorkspaceCommand(normalized.command, this.directory(entry)), options, normalized.cwd);
  }
  async uploadFiles(scope: SandboxScope, id: string, files: SandboxFile[]) {
    const entry = await this.entry(scope, id);
    if (files.length > 500 || files.reduce((sum, file) => sum + Buffer.byteLength(file.content), 0) > 20_000_000) throw new SandboxProviderError("upload_limit", "Project exceeds workspace sync limits", 413);
    const sanitized = files.map(file => ({ path: safeProjectPath(file.path), content: file.content }));
    // Run file synchronization through the same OS boundary as project code.
    // A malicious symlink/race cannot make the root supervisor write elsewhere.
    const script = `const fs=require('fs'),p=require('path');let b='';process.stdin.on('data',c=>b+=c);process.stdin.on('end',()=>{const files=JSON.parse(b),keep=new Set(files.map(f=>f.path));for(const f of files){const target=p.resolve(f.path);let parent=p.dirname(target);fs.mkdirSync(parent,{recursive:true});const temp=p.join(parent,'.npati-upload-'+require('crypto').randomUUID());fs.writeFileSync(temp,f.content,{flag:'wx',mode:0o600});fs.renameSync(temp,target)}function clean(dir){for(const item of fs.readdirSync(dir,{withFileTypes:true})){if(${excluded}.test(item.name))continue;const file=p.join(dir,item.name);if(item.isDirectory())clean(file);else if(!keep.has(file))fs.unlinkSync(file)}}clean('.')});`;
    const result = await this.collect(entry, "node", ["-e", script], JSON.stringify(sanitized), { timeoutMs: 120000, outputLimitBytes: 64000 });
    if (result.exitCode !== 0) throw new SandboxProviderError("workspace_sync_failed", result.stderr.slice(0, 1000), 403);
  }
  async downloadFiles(scope: SandboxScope, id: string) {
    const entry = await this.entry(scope, id);
    const script = `const fs=require('fs'),p=require('path');const files=[];let bytes=0;function walk(dir){for(const f of fs.readdirSync(dir,{withFileTypes:true})){if(${excluded}.test(f.name))continue;const file=p.join(dir,f.name);if(f.isSymbolicLink())throw Error('Project symlink denied');if(f.isDirectory())walk(file);else if(f.isFile()){const data=fs.readFileSync(file);bytes+=data.length;if(bytes>20000000||files.length>=500)throw Error('Workspace sync limit');const content=new TextDecoder('utf-8',{fatal:true}).decode(data);if(content.includes('\\0'))throw Error('Binary file denied');files.push({path:file,content})}}}walk('.');process.stdout.write(JSON.stringify(files));`;
    const result = await this.collect(entry, "node", ["-e", script], "", { timeoutMs: 120000, outputLimitBytes: 32_000_000 });
    if (result.exitCode !== 0) throw new SandboxProviderError("workspace_sync_failed", result.stderr.slice(0, 1000), 403);
    return JSON.parse(result.stdout) as SandboxFile[];
  }
  async exposePort(scope: SandboxScope, id: string, requestedPort: number) {
    if (!Number.isInteger(requestedPort) || requestedPort < 1024 || requestedPort > 65535) throw new SandboxProviderError("invalid_port", "Invalid preview port", 400);
    const entry = await this.entry(scope, id);
    return { port: entry.port, internalHost: "127.0.0.1" };
  }
  async proxyPreview(scope: SandboxScope, id: string, options: PreviewProxyRequest): Promise<PreviewProxyResponse> {
    const entry = await this.entry(scope, id);
    if (options.port !== entry.port) throw new SandboxProviderError("project_port_denied", "Preview port belongs to another Project", 403);
    if (!options.path.startsWith("/") || options.path.startsWith("//") || /[\\\r\n]/.test(options.path) || options.path.length > 4096 || !["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE"].includes(options.method) || (options.body?.length ?? 0) > 8_000_000) throw new SandboxProviderError("invalid_preview_request", "Invalid preview request", 400);
    const url = new URL(options.path, `http://127.0.0.1:${entry.port}`);
    if (url.hostname !== "127.0.0.1" || Number(url.port) !== entry.port) throw new SandboxProviderError("project_port_denied", "Invalid Preview destination", 403);
    try {
      const response = await fetch(url, { method: options.method, headers: options.headers, body: options.body ? Buffer.from(options.body, "base64") : undefined, redirect: "manual", signal: AbortSignal.timeout(20000) });
      const body = Buffer.from(await response.arrayBuffer());
      if (body.length > 8_000_000) throw new SandboxProviderError("preview_response_limit", "Preview response too large", 413);
      const headers: Record<string, string> = {}; response.headers.forEach((value, key) => { headers[key] = value; });
      return { status: response.status, headers, body: body.toString("base64") };
    } catch (error) { if (error instanceof SandboxProviderError) throw error; throw new SandboxProviderError("preview_upstream_failed", "Project Preview server unavailable", 502); }
  }
  async startProcess(scope: SandboxScope, id: string, command: string, options: SandboxCommandOptions): Promise<SandboxCommandResult> {
    const entry = await this.entry(scope, id), normalized = this.command(command, options.cwd);
    sandboxProcessEnvironment(options.environment);
    const processId = randomUUID();
    const log = await open(path.join(this.state, `${processId}.log`), "wx", 0o600);
    const child = this.launch(entry, "sh", ["-s"], normalized.cwd, options.environment, true);
    const record: ProcessRecord = { id: processId, pid: child.pid, status: "running", exitCode: null };
    entry.processes[processId] = record; this.children.set(processId, child);
    let written = 0;
    const append = (chunk: Buffer) => { const available = Math.max(0, 2_000_000 - written); written += chunk.length; if (available) void log.write(chunk.subarray(0, available)).catch(() => undefined); };
    child.stdout!.on("data", append); child.stderr!.on("data", append);
    child.on("error", () => { record.status = "failed"; record.exitCode = 126; });
    child.on("close", code => { if (record.status === "running") record.status = code === 0 ? "completed" : "failed"; record.exitCode = code; this.children.delete(processId); void log.close().catch(() => undefined); void this.persist().catch(() => undefined); });
    child.stdin!.on("error", () => undefined);
    // Preview servers are long-lived; command timeouts apply to foreground jobs.
    child.stdin!.end(projectRuntimeWorkspaceCommand(projectRuntimeCommandPort(normalized.command, entry.port), this.directory(entry)));
    await this.persist();
    return this.processResult(record);
  }
  private processResult(record: ProcessRecord): SandboxCommandResult { return { status: record.status, exitCode: record.exitCode, stdout: "", stderr: "", durationMs: 0, step: "process", tool: "project.terminal.process", retryable: false, processId: record.id }; }
  private process(entry: Entry, id: string) { const record = entry.processes[id]; if (!record) throw new SandboxProviderError("process_not_found", "Process does not belong to selected Project", 404); return record; }
  async getProcessStatus(scope: SandboxScope, id: string, processId: string) { return this.processResult(this.process(await this.entry(scope, id), processId)); }
  async stopProcess(scope: SandboxScope, id: string, processId: string) {
    const entry = await this.entry(scope, id), record = this.process(entry, processId), child = this.children.get(processId);
    // Never signal persisted PIDs after supervisor restart (PID reuse).
    if (child?.pid && record.status === "running") { try { process.kill(-child.pid, "SIGKILL"); } catch { /* already stopped */ } }
    record.status = "stopped"; await this.persist(); return this.processResult(record);
  }
  async getLogs(scope: SandboxScope, id: string, processId?: string) {
    const entry = await this.entry(scope, id);
    if (!processId) return "";
    this.process(entry, processId);
    return readFile(path.join(this.state, `${processId}.log`), "utf8");
  }
}
