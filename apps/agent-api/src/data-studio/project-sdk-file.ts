import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { AuthContext } from "@npati/workspace";
import type { ProjectWorkspace } from "../project-workspace";

/**
 * Project client SDK delivery (D5).
 *
 * Generated sites and apps run inside the sandbox, which cannot install the private
 * `@npati/project-client` workspace package from a registry. The SDK source is therefore
 * vendored into the Project workspace as a single TypeScript file that the sandbox syncs
 * like any other project file, so generated code can import it locally.
 */
export const PROJECT_SDK_FILE_NAME = "npati-client.ts";
/** Specifier generated frontends should import. */
export const PROJECT_SDK_IMPORT_PATH = "./npati-client";

const CONTAINER_SDK_PATH = "/opt/npati-project-sdk/index.ts";
const MAX_DEPTH = 8;

function candidatePaths(): string[] {
  const candidates: string[] = [];
  const configured = process.env.NPATI_PROJECT_CLIENT_PATH;
  if (configured) candidates.push(configured);
  candidates.push(CONTAINER_SDK_PATH);
  let current = path.dirname(fileURLToPath(import.meta.url));
  for (let depth = 0; depth < MAX_DEPTH; depth += 1) {
    candidates.push(path.join(current, "packages", "project-client", "src", "index.ts"));
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
  return candidates;
}

/** Reads the SDK source from the first available location; null when the deployment lacks it. */
export async function loadProjectClientSdkSource(): Promise<string | null> {
  for (const candidate of candidatePaths()) {
    try {
      const content = await readFile(candidate, "utf8");
      if (content.trim()) return content;
    } catch {
      // Try the next candidate location.
    }
  }
  return null;
}

export function renderProjectSdkFile(source: string): string {
  return [
    "// Generated by NPATI Data Studio. Do not edit: this Project API client is regenerated",
    "// from the @npati/project-client package and only reflects the DataBackend of this Project.",
    source,
  ].join("\n");
}

export type ProjectSdkSyncResult = "written" | "unchanged" | "unavailable";

/**
 * Ensures the Project workspace contains the current SDK file so the sandbox and generated
 * code can import it. Never throws for a missing SDK: Preview and Terminal keep working.
 */
export async function ensureProjectSdkFile(
  ctx: AuthContext,
  companyId: string,
  projectId: string,
  workspace?: Pick<ProjectWorkspace, "readFile" | "createFile" | "writeFile">,
): Promise<ProjectSdkSyncResult> {
  if (!workspace) return "unavailable";
  const source = await loadProjectClientSdkSource();
  if (!source) {
    console.warn("[project-sdk] Project client SDK source was not found; generated sites cannot import the SDK");
    return "unavailable";
  }
  const content = renderProjectSdkFile(source);
  let existing: { content: string; revision: string } | undefined;
  try {
    const file = await workspace.readFile(ctx, companyId, projectId, PROJECT_SDK_FILE_NAME);
    existing = { content: file.content, revision: file.revision };
  } catch {
    existing = undefined;
  }
  if (existing && existing.content === content) return "unchanged";
  if (existing) await workspace.writeFile(ctx, companyId, projectId, PROJECT_SDK_FILE_NAME, content, existing.revision);
  else await workspace.createFile(ctx, companyId, projectId, PROJECT_SDK_FILE_NAME, content);
  return "written";
}
