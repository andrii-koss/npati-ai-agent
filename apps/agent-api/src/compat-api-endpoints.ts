import { randomUUID } from "node:crypto";

export interface AnthropicMessageParam {
  role: "user" | "assistant";
  content: string | Array<{ type: "text" | "image" | "tool_use" | "tool_result"; text?: string }>;
}

export interface AnthropicMessagesRequest {
  model: string;
  messages: AnthropicMessageParam[];
  system?: string;
  max_tokens?: number;
  temperature?: number;
  tools?: Array<{
    name: string;
    description: string;
    input_schema: Record<string, any>;
  }>;
}

export interface AnthropicMessagesResponse {
  id: string;
  type: "message";
  role: "assistant";
  content: Array<{ type: "text"; text: string }>;
  model: string;
  stop_reason: "end_turn" | "max_tokens" | "tool_use";
  usage: {
    input_tokens: number;
    output_tokens: number;
  };
}

export interface GeminiContentPart {
  text?: string;
  inlineData?: { mimeType: string; data: string };
}

export interface GeminiContent {
  role: "user" | "model";
  parts: GeminiContentPart[];
}

export interface GeminiGenerateContentRequest {
  contents: GeminiContent[];
  generationConfig?: {
    temperature?: number;
    maxOutputTokens?: number;
    topP?: number;
  };
}

export interface GeminiGenerateContentResponse {
  candidates: Array<{
    content: {
      role: "model";
      parts: Array<{ text: string }>;
    };
    finishReason: "STOP" | "MAX_TOKENS";
    index: number;
  }>;
  usageMetadata: {
    promptTokenCount: number;
    candidatesTokenCount: number;
    totalTokenCount: number;
  };
}

export class AnthropicMessagesHandler {
  /**
   * 1. Anthropic Messages API (/v1/messages) Compatible Handler
   */
  static async handleRequest(
    req: AnthropicMessagesRequest,
    customExecutor?: (system: string, userText: string, model: string) => Promise<string>
  ): Promise<AnthropicMessagesResponse> {
    const system = req.system || "";
    const lastUserMessage = req.messages.filter((m) => m.role === "user").pop();
    const userText =
      typeof lastUserMessage?.content === "string"
        ? lastUserMessage.content
        : lastUserMessage?.content?.[0]?.text || "";

    let responseText = `Anthropic response generated by model: ${req.model}`;

    if (customExecutor) {
      responseText = await customExecutor(system, userText, req.model);
    }

    const inputTokens = Math.ceil((system.length + userText.length) / 4);
    const outputTokens = Math.ceil(responseText.length / 4);

    return {
      id: `msg_${randomUUID().replace(/-/g, "").slice(0, 16)}`,
      type: "message",
      role: "assistant",
      content: [{ type: "text", text: responseText }],
      model: req.model,
      stop_reason: "end_turn",
      usage: {
        input_tokens: inputTokens,
        output_tokens: outputTokens,
      },
    };
  }
}

export class GeminiGenerateContentHandler {
  /**
   * 2. Google Gemini (/v1beta/models/...:generateContent) Compatible Handler
   */
  static async handleRequest(
    model: string,
    req: GeminiGenerateContentRequest,
    customExecutor?: (prompt: string, model: string) => Promise<string>
  ): Promise<GeminiGenerateContentResponse> {
    const allParts: string[] = [];
    for (const c of req.contents) {
      for (const p of c.parts) {
        if (p.text) allParts.push(p.text);
      }
    }

    const fullPrompt = allParts.join("\n");
    let responseText = `Gemini response generated by model: ${model}`;

    if (customExecutor) {
      responseText = await customExecutor(fullPrompt, model);
    }

    const promptTokens = Math.ceil(fullPrompt.length / 4);
    const candidateTokens = Math.ceil(responseText.length / 4);

    return {
      candidates: [
        {
          content: {
            role: "model",
            parts: [{ text: responseText }],
          },
          finishReason: "STOP",
          index: 0,
        },
      ],
      usageMetadata: {
        promptTokenCount: promptTokens,
        candidatesTokenCount: candidateTokens,
        totalTokenCount: promptTokens + candidateTokens,
      },
    };
  }
}
