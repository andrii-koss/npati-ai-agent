import { createHash } from "node:crypto";
import { scanTextForSecrets } from "./code-secret-scanner";

/**
 * C8 — `init`: propose a `NPATI.md` draft for a repository.
 *
 * `init` never writes. It analyses what the harness already knows about the project (the C1 toolchain
 * detection, the top-level layout, the verify commands) and returns a draft plus the hash of that draft. The
 * write is a *separate* act that goes through the existing `code.fs.write` path, which means it is authorised by
 * RBAC, classified by the PolicyEngine and, where the mode requires it, gated by an approval like every other
 * write. That is deliberate: a command that could create a file influencing future system prompts must not be
 * able to bypass the mechanism that governs file writes.
 *
 * The draft is deterministic: the same facts produce the same bytes, so a re-run is diffable rather than noisy.
 */

export const INSTRUCTIONS_INIT_SCHEMA_VERSION = 1;
/** The draft is always proposed for this path; `init` does not invent file names. */
export const INSTRUCTIONS_DRAFT_PATH = "NPATI.md";
export const MAX_DRAFT_CHARS = 6_000;

export class InstructionsDraftSecretError extends Error {
  constructor(readonly kinds: string[]) {
    super("Generated instructions draft contains a credential");
    this.name = "InstructionsDraftSecretError";
  }
}

export interface InstructionsDraftInput {
  projectName: string;
  /** Facts from the existing C1 toolchain detection, passed through unchanged. */
  toolchain?: {
    languages?: readonly string[];
    packageManagers?: readonly string[];
    verifyCommands?: { install?: string; build?: string; test?: string; lint?: string; typecheck?: string };
  } | null;
  /** Top-level entries observed in the workspace, used only as a hint list (bounded, never recursive). */
  topLevelPaths?: readonly string[];
  /** Extra lines the caller wants surfaced (e.g. an existing note), always treated as data. */
  notes?: readonly string[];
}

export interface InstructionsDraft {
  schemaVersion: number;
  path: string;
  content: string;
  contentHash: `sha256:${string}`;
  /** Always true: creating this file is a write, and writes are authorised and auditable. */
  requiresApproval: true;
  /** The path the caller must use to persist the draft; `init` itself never writes. */
  writeVia: "code.fs.write";
  /** What the draft was derived from, for the UI. */
  generatedFrom: string[];
  truncated: boolean;
}

function sha256(value: string): `sha256:${string}` {
  return `sha256:${createHash("sha256").update(value, "utf8").digest("hex")}`;
}

function bullet(values: readonly string[] | undefined, fallback: string): string {
  const list = (values ?? []).map((value) => String(value).trim()).filter(Boolean);
  if (list.length === 0) return `- ${fallback}`;
  return list.map((value) => `- ${value}`).join("\n");
}

/**
 * Build the draft. Every value is escaped into a plain line: the draft is markdown the user will read, and the
 * inputs are repository facts, so nothing here interprets them as markup or as instructions.
 */
export function buildInstructionsDraft(input: InstructionsDraftInput): InstructionsDraft {
  const generatedFrom: string[] = [];
  const toolchain = input.toolchain ?? null;
  const languages = toolchain?.languages ?? [];
  const packageManagers = toolchain?.packageManagers ?? [];
  if (languages.length > 0) generatedFrom.push("toolchain.languages");
  if (packageManagers.length > 0) generatedFrom.push("toolchain.packageManagers");
  const verify = toolchain?.verifyCommands ?? {};
  const verifyLines = Object.entries(verify)
    .filter(([, value]) => typeof value === "string" && value.trim().length > 0)
    .map(([name, value]) => `- ${name}: \`${String(value).trim()}\``);
  if (verifyLines.length > 0) generatedFrom.push("toolchain.verifyCommands");

  const topLevel = (input.topLevelPaths ?? []).map((entry) => String(entry).trim()).filter(Boolean).slice(0, 40);
  if (topLevel.length > 0) generatedFrom.push("workspace.topLevelPaths");
  if ((input.notes ?? []).length > 0) generatedFrom.push("notes");

  const lines: string[] = [
    `# ${input.projectName.trim() || "Project"} — agent instructions`,
    "",
    "<!-- Generated by the NPATI Coding Agent (`init`). Edit freely: this file guides the CONTENT of the work only.",
    "     It can never change permissions, the session mode, the tool list, policies or hooks. -->",
    "",
    "## Stack",
    bullet(languages, "not detected — fill in the languages this project uses"),
    "",
    "Package managers:",
    bullet(packageManagers, "not detected"),
    "",
    "## Commands",
    verifyLines.length > 0 ? verifyLines.join("\n") : "- not detected — document install, build, test and lint here",
    "",
    "## Layout",
    topLevel.length > 0 ? topLevel.map((entry) => `- \`${entry}\``).join("\n") : "- not detected",
    "",
    "## Conventions",
    "- Follow the existing style of the files you touch.",
    "- Keep changes scoped to the task; do not reformat unrelated code.",
    "- Prefer the project's own scripts over ad-hoc commands.",
    "",
    "## Notes",
    ...((input.notes ?? []).map((note) => `- ${String(note).trim()}`).filter((line) => line !== "- ")),
  ];

  if ((input.notes ?? []).length === 0) lines.push("- none");

  let content = `${lines.join("\n")}\n`;
  let truncated = false;
  if (content.length > MAX_DRAFT_CHARS) {
    content = `${content.slice(0, MAX_DRAFT_CHARS)}\n…[draft truncated]\n`;
    truncated = true;
  }

  const findings = scanTextForSecrets(content).findings;
  if (findings.length > 0) {
    // The draft is derived from repository facts, so it can inherit a credential from them. Refuse loudly:
    // a draft is shown to the user and may be written to disk, so shipping a credential inside it is worse
    // than not producing a draft.
    throw new InstructionsDraftSecretError(Array.from(new Set(findings.map((finding) => String(finding.kind)))));
  }

  return {
    schemaVersion: INSTRUCTIONS_INIT_SCHEMA_VERSION,
    path: INSTRUCTIONS_DRAFT_PATH,
    content,
    contentHash: sha256(content),
    requiresApproval: true,
    writeVia: "code.fs.write",
    generatedFrom,
    truncated,
  };
}
