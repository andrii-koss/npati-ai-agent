check("a complete dataset => preparation generates nothing", second.generated === false && second.ok === true && second.missing.length === 0);
const staleFile = path.join(root, "data", "typosquat", "npm.json");
const stale = JSON.parse(readFileSync(staleFile, "utf8"));
stale.packageNames = [...stale.packageNames, "left-pad-not-in-the-curated-list"];
writeFileSync(staleFile, `${JSON.stringify(stale, null, 2)}\n`, "utf8");
const third = prepareTyposquatDataset({ root });
check("a stale dataset is not rewritten by the preparation phase", third.generated === false);
check("the guard still refuses the stale dataset (--check exit 1)", runCheck(root) === 1);
rmSync(root, { recursive: true, force: true });

