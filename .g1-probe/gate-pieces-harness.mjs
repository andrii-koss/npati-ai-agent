/**
 * TEMP standalone harness (G1 item 5). Not a gate suite: it exercises the pieces of the real verdict that
 * vitest cannot run in this session, because the sandbox denies `child_process` stdio **pipes** and
 * vitest/esbuild cannot start there.
 *
 * Run: node .g1-probe/gate-pieces-harness.mjs
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const { SECURITY_GATE_TESTS, prepareTyposquatDataset } = await import("../scripts/lib/run-security-gate.mjs");

const results = [];
const check = (label, condition) => results.push({ label, ok: Boolean(condition) });

function cleanTree(label) {
  const root = mkdtempSync(path.join(tmpdir(), `npati-harness-${label}-`));
  for (const file of [
    "scripts/typosquat-dataset-generate.mjs",
    "scripts/lib/typosquat-dataset-generate.mjs",
    "scripts/lib/run-security-gate.mjs",
  ]) {
    const target = path.join(root, ...file.split("/"));
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, readFileSync(path.join(ROOT, ...file.split("/"))), "utf8");
  }
  return root;
}

/** The generator as the runbook runs it: `stdio: "inherit"`, which the sandbox allows. */
function generate(root) {
  const generator = path.join(root, "scripts", "typosquat-dataset-generate.mjs");
  return spawnSync(process.execPath, [generator, "--root", root], { cwd: root, stdio: ["ignore", "inherit", "inherit"] }).status;
}

function runCheck(root) {
  const generator = path.join(root, "scripts", "typosquat-dataset-generate.mjs");
  const result = spawnSync(process.execPath, [generator, "--check", "--root", root], { cwd: root, stdio: ["ignore", "inherit", "inherit"] });
  return result.status;
}

const ecosystems = ["npm", "pypi", "cargo", "go", "composer", "maven"];

// --- 1. the generator produces the real dataset for the tree it is told about ---------------------------------
const root = cleanTree("clean");
check("no data/ in the clean tree", !existsSync(path.join(root, "data")));
check("generator exit 0", generate(root) === 0);
check("six dataset files exist", ecosystems.every((e) => existsSync(path.join(root, "data", "typosquat", `${e}.json`))));

// Hash consistency, computed here with the same canonical rule the loader uses (no data/ dependency).
function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value ?? null);
  if (Array.isArray(value)) return `[${value.map((item) => canonicalJson(item)).join(",")}]`;
  const entries = Object.entries(value).filter(([, item]) => item !== undefined).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([key, item]) => `${JSON.stringify(key)}:${canonicalJson(item)}`).join(",")}}`;
}
const hashOf = (names) => `sha256:${createHash("sha256").update(canonicalJson([...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))), "utf8").digest("hex")}`;
let hashesOk = true;
let namesOk = true;
let identical = true;
for (const ecosystem of ecosystems) {
  const serialized = readFileSync(path.join(root, "data", "typosquat", `${ecosystem}.json`), "utf8");
  const dataset = JSON.parse(serialized);
  if (dataset.hash !== hashOf(dataset.packageNames)) hashesOk = false;
  if (dataset.ecosystem !== ecosystem || dataset.packageNames.length < 40) namesOk = false;
  const repositoryFile = path.join(ROOT, "data", "typosquat", `${ecosystem}.json`);
  if (!existsSync(repositoryFile) || readFileSync(repositoryFile, "utf8") !== serialized) identical = false;
}
check("every generated hash matches its names", hashesOk);
check("every generated file names its ecosystem and has >= 40 names", namesOk);
check("the generated bytes are identical to the repository's dataset", identical);
check("the generated tree passes the guard (--check exit 0)", runCheck(root) === 0);

