/** Every `from "…"` / `import("…")` relative specifier in a source file, resolved to a repo-relative path. */
function relativeImports(file) {
  const source = readFileSync(path.join(ROOT, ...file.split("/")), "utf8");
  const out = [];
  for (const match of source.matchAll(/(?:from|import)\s*\(?\s*"([^"]+)"/g)) {
    const specifier = match[1];
    if (!specifier.startsWith(".")) continue;
    const resolved = path.relative(ROOT, path.resolve(path.dirname(path.join(ROOT, ...file.split("/"))), specifier)).split(path.sep).join("/");
    out.push(resolved);
  }
  return out;
}

/** The shebang-bearing files reachable from one suite, so "the import graph" is measured, not guessed. */
function shebangReachability(suite) {
  const seen = new Set();
  const offenders = [];
  const queue = [suite];
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    let imports = [];
    try {
      imports = relativeImports(file);
    } catch {
      continue;
    }
    for (const next of imports) {
      if (next.endsWith(".mjs") && !next.startsWith("scripts/lib/")) {
        try {
          if (readFileSync(path.join(ROOT, ...next.split("/")), "utf8").startsWith("#!")) offenders.push(`${suite} -> ${next}`);
        } catch {
          // A module that does not exist is a different defect (the gate's suite-file check covers it).
        }
      }
      queue.push(next);
    }
  }
  return offenders;
}

const graphOffenders = [];
for (const suite of gateSuites) graphOffenders.push(...shebangReachability(suite));
