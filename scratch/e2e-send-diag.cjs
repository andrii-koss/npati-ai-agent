const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const token = fs.readFileSync('scratch/e2e-token.txt', 'utf8').trim();
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(t => {
    localStorage.setItem('npati_agent_access_token', t);
    localStorage.setItem('npati_agent_user', JSON.stringify({ id: '599402b8-b9d5-4676-a391-7b9db1a77026', email: 'dev@npati.local', username: 'dev', displayName: 'Dev User', role: 'owner' }));
    localStorage.setItem('npati_selected_company_id_v1', 'e8fb3cc1-4809-4c95-a10a-1c7e2a57913b');
    sessionStorage.setItem('npati_selected_company_id_v1', 'e8fb3cc1-4809-4c95-a10a-1c7e2a57913b');
  }, token);
  const page = await context.newPage();
  page.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0, 500)));
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  page.on('request', r => { if (r.url().includes('/api/')) console.log('REQ', r.method(), r.url().slice(0, 200)); });
  page.on('response', r => { if (r.url().includes('/api/')) console.log('RESP', r.status(), r.url().slice(0, 200)); });
  await page.goto('http://127.0.0.1:13001/chat', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForSelector('textarea', { timeout: 30000 });
  await page.waitForTimeout(3000);
  console.log('SELECT', await page.locator('select[aria-label="Active context"]').inputValue().catch(e => 'ERR ' + e.message));
  const prompt = 'Створи сучасний адаптивний тестовий сайт на Vue 3 + Vite. Додай головну сторінку.';
  await page.locator('textarea').first().fill(prompt);
  await page.waitForTimeout(500);
  console.log('TEXTAREA', await page.locator('textarea').first().inputValue());
  console.log('SEND COUNT', await page.locator('button[aria-label="Send"]').count(), 'DISABLED', await page.locator('button[aria-label="Send"]').isDisabled().catch(() => 'n/a'));
  await page.locator('button[aria-label="Send"]').click();
  await page.waitForTimeout(10000);
  console.log('URL', page.url());
  console.log('BODY', (await page.locator('body').innerText()).slice(-2500));
  await page.screenshot({ path: 'scratch/chat-after-send.png', fullPage: true });
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
