import { describe, expect, it } from "vitest";
import {
  AdaptiveAdmissionQueue,
  SelfHealingAutoCombo,
} from "../apps/agent-api/src/resilience-admission-queue";
import { PersistentConversationMemory } from "../apps/agent-api/src/persistent-conversation-memory";

describe("Adaptive Admission Queue (AdaptiveAdmissionQueue)", () => {
  it("processes tasks by priority tier and enforces concurrency limits", async () => {
    const queue = new AdaptiveAdmissionQueue({ maxConcurrent: 2 });
    const executionOrder: string[] = [];

    const makeTask = (id: string, delayMs: number) => async () => {
      await new Promise((r) => setTimeout(r, delayMs));
      executionOrder.push(id);
      return id;
    };

    // Enqueue 4 tasks simultaneously with different priority tiers
    const pFree = queue.enqueue(makeTask("free-1", 50), "free");
    const pPro = queue.enqueue(makeTask("pro-1", 30), "pro");
    const pEnterprise = queue.enqueue(makeTask("enterprise-1", 20), "enterprise");

    const results = await Promise.all([pFree, pPro, pEnterprise]);
    expect(results).toEqual(["free-1", "pro-1", "enterprise-1"]);
    expect(executionOrder.length).toBe(3);
  });
});

describe("Self-Healing Auto-Combo (SelfHealingAutoCombo)", () => {
  it("transparently heals execution when primary model fails", async () => {
    const candidates = [
      {
        modelId: "openai/gpt-4o",
        provider: "openai",
        execute: async () => {
          throw new Error("503 Service Unavailable");
        },
      },
      {
        modelId: "anthropic/claude-3-7-sonnet",
        provider: "anthropic",
        execute: async () => "Healed response generated by Claude 3.7 Sonnet.",
      },
    ];

    const result = await SelfHealingAutoCombo.executeWithHealing(candidates);

    expect(result.wasHealed).toBe(true);
    expect(result.finalModelId).toBe("anthropic/claude-3-7-sonnet");
    expect(result.result).toBe("Healed response generated by Claude 3.7 Sonnet.");
    expect(result.attempts.length).toBe(2);
    expect(result.attempts[0].success).toBe(false);
    expect(result.attempts[1].success).toBe(true);
  });
});

describe("Persistent Conversation Memory (PersistentConversationMemory)", () => {
  it("maintains session history and compacts sliding dialogue window", () => {
    const memory = new PersistentConversationMemory();
    const sessionId = "session-test-multi";
    const companyId = "comp-mem";
    const tenantId = "tenant-mem";

    // Set window to 15 tokens to trigger compaction after multiple turns
    memory.getOrCreateSession(sessionId, companyId, tenantId, 15);

    memory.appendMessage(sessionId, companyId, tenantId, "user", "Message 1: What is NPATI?");
    memory.appendMessage(sessionId, companyId, tenantId, "assistant", "Message 2: NPATI is an AI Agent Platform.");
    memory.appendMessage(sessionId, companyId, tenantId, "user", "Message 3: Can it route models?");
    memory.appendMessage(sessionId, companyId, tenantId, "assistant", "Message 4: Yes, using Auto-Combo and LKGP.");
    memory.appendMessage(sessionId, companyId, tenantId, "user", "Message 5: What about memory injection?");

    const context = memory.getContextMessages(sessionId, companyId, tenantId);
    expect(context.length).toBeGreaterThan(0);

    // Summary context should be present after compaction
    const session = memory.getOrCreateSession(sessionId, companyId, tenantId);
    expect(session.summaryContext).toBeDefined();
    expect(session.summaryContext).toContain("Previous Discussion Summary");
  });
});
